from __future__ import annotations

from datetime import UTC, datetime
from enum import StrEnum
from hashlib import sha256
from typing import Any, Literal
from uuid import uuid4

from pydantic import BaseModel, ConfigDict, Field, model_validator


class Domain(StrEnum):
    BILLING = "billing"
    CONNECTIVITY = "connectivity"
    ACCOUNT = "account"
    POLICY = "policy"


class FailureLabel(StrEnum):
    HALLUCINATION = "HALLUCINATION"
    STALE_CONTEXT = "STALE_CONTEXT"
    MISSING_CONTEXT = "MISSING_CONTEXT"
    ROUTING = "ROUTING"
    TOOL_FAILURE = "TOOL_FAILURE"
    TOOL_AUTHORIZATION = "TOOL_AUTHORIZATION"
    POLICY_COMPLIANCE = "POLICY_COMPLIANCE"
    SAFETY = "SAFETY"
    KNOWLEDGE_COVERAGE = "KNOWLEDGE_COVERAGE"
    MEMORY_CONTAMINATION = "MEMORY_CONTAMINATION"
    LATENCY_COST = "LATENCY_COST"
    EVAL_INFRA = "EVAL_INFRA"
    OTHER = "OTHER"


class RunRequest(BaseModel):
    model_config = ConfigDict(extra="forbid")

    tenant_id: str = Field(min_length=2)
    principal_id: str = Field(min_length=2)
    correlation_id: str = Field(min_length=4)
    customer_id: str = Field(min_length=2)
    message: str = Field(min_length=3, max_length=4000)
    scopes: set[str] = Field(
        default_factory=lambda: {
            "customer:read",
            "billing:read",
            "service:read",
            "policy:read",
        }
    )
    policy_version: str = "policy-2026-10"
    inject_fault: str | None = None
    approval_id: str | None = None


class RunResult(BaseModel):
    run_id: str = Field(default_factory=lambda: str(uuid4()))
    status: Literal["completed", "approval_required", "denied", "failed"]
    route: list[Domain]
    answer: str
    policy_version: str
    approval_id: str | None = None
    trace_id: str
    tool_results: list[dict[str, Any]] = Field(default_factory=list)


class ApprovalDecision(BaseModel):
    approval_id: str
    tenant_id: str
    principal_id: str
    role: str
    approved: bool
    exact_parameters_hash: str
    decided_at: datetime = Field(default_factory=lambda: datetime.now(UTC))


class Case(BaseModel):
    case_id: str
    incident_family: str
    split: Literal["development", "calibration", "held_out"]
    domain: Domain
    message: str
    expected_route: list[Domain]
    expected_policy_version: str = "policy-2026-10"
    expected_approval: bool = False
    expected_failure: FailureLabel | None = None
    criticality: Literal["low", "medium", "high", "critical"] = "medium"
    source_version: str = "synthetic-v1"
    provenance: str = "generated by deterministic dataset builder"


class EvaluationRecord(BaseModel):
    case_id: str
    passed: bool
    route_ok: bool
    policy_ok: bool
    approval_ok: bool
    authorization_ok: bool
    grounded: bool
    latency_ms: int
    token_cost_units: int
    failure_label: FailureLabel | None = None


class VariantManifest(BaseModel):
    variant_id: str = Field(default_factory=lambda: str(uuid4()))
    baseline_version: str
    lane: Literal["harness", "context", "routing", "model"]
    changed_factor: str
    diff: dict[str, Any]
    owner: str
    expected_effect: str
    failure_evidence: list[str]
    golden_set_id: str
    primary_metric: str
    guardrails: list[str]
    risks: list[str]
    reversal_plan: str
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    content_hash: str = ""

    @model_validator(mode="after")
    def add_content_hash(self) -> VariantManifest:
        if not self.content_hash:
            payload = self.model_dump_json(exclude={"content_hash"}, exclude_none=True)
            self.content_hash = sha256(payload.encode()).hexdigest()
        return self


class ReleaseDecision(BaseModel):
    allowed: bool
    hard_gate_failures: list[str]
    metric_delta: float
    reason: str
